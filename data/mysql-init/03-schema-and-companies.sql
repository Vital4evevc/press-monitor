-- Full bootstrap for the press-monitor database: schema plus the seed company list.
--
-- The point of this file is that a fresh database ends up in a runnable state WITHOUT the
-- backend ever having started. Normally two startup side effects do this work: Hibernate
-- creates company/mention from the JPA entities (ddl-auto: update), and CompanySeedLoader
-- upserts companies.csv on ApplicationReadyEvent. Both are reproduced here.
--
-- The DDL mirrors the Company and Mention entities in press-monitor-shared, including the
-- indexes and the unique constraint declared on them. Hibernate still runs with
-- ddl-auto: update afterwards; because these tables already match, it finds nothing to do.
-- If you change an entity, change this file too or the two drift apart.
--
-- The 258 company rows below are generated from backend/src/main/resources/companies.csv,
-- with ids produced by the same slug rule CompanySeedLoader.slugify uses (NFD normalize,
-- strip accents, lowercase, non-alphanumerics to '-', trim leading/trailing '-').
--
-- Deliberately NOT included: the mention table's contents. Mentions are collected output,
-- not input the app needs to run — they come from Google News plus the classifier at
-- runtime. Use ./seed-db.sh --export to capture those from a live database.
--
-- Idempotent: safe to run against an existing database. Mounted at
-- /docker-entrypoint-initdb.d so it also runs automatically on a fresh MySQL volume.

USE pressmonitor;

CREATE TABLE IF NOT EXISTS company (
    id          VARCHAR(128) NOT NULL,
    name        VARCHAR(256) NOT NULL,
    search_hint VARCHAR(256) DEFAULT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY idx_company_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS mention (
    id                   BIGINT       NOT NULL AUTO_INCREMENT,
    company_id           VARCHAR(128) NOT NULL,
    title                VARCHAR(1024) NOT NULL,
    snippet              TEXT,
    url                  VARCHAR(2048),
    source               VARCHAR(256),
    published_at         DATETIME(6),
    collected_at         DATETIME(6)  NOT NULL,
    -- Sentiment is persisted as its enum name: POSITIVE, NEGATIVE, NEUTRAL or UNKNOWN.
    sentiment            VARCHAR(16)  NOT NULL,
    sentiment_confidence DOUBLE,
    sentiment_reason     VARCHAR(1024),
    -- SHA-256 of the article URL, falling back to the title. Paired with company_id this is
    -- what stops a re-run storing the same article twice.
    dedup_key            VARCHAR(64)  NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_mention_company_dedup (company_id, dedup_key),
    KEY idx_mention_company (company_id),
    KEY idx_mention_published (published_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

